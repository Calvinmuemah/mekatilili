CREATE TABLE IF NOT EXISTS quest_objectives (
    id VARCHAR(100) PRIMARY KEY,
    quest_id VARCHAR(100) REFERENCES quests(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    objective_type VARCHAR(50) NOT NULL DEFAULT 'CUSTOM', -- TALK_TO_NPC, VISIT_LOCATION, COLLECT_ITEM, REACH_LOCATION, COMPLETE_DIALOGUE, TRIGGER_EVENT, CUSTOM
    required BOOLEAN DEFAULT TRUE,
    order_index INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_objectives_quest ON quest_objectives(quest_id);
